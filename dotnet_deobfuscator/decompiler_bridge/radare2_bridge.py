"""
Radare2 and Cutter Disassembler Bridge Script & Batch Runner Generator.
Engineered & Audited by Maya Thorne.
"""

import re
from typing import List

from .models import DecompilerBookmark, DecompilerComment, DecompilerSymbol


class Radare2BridgeGenerator:
    """Generates Radare2 / Cutter command scripts (.r2) and batch runners."""

    @staticmethod
    def sanitize_flag(name: str) -> str:
        """Sanitizes flag names for radare2 flag spaces."""
        clean = re.sub(r"[^a-zA-Z0-9_.]", "_", name)
        clean = re.sub(r"_+", "_", clean).strip("_")
        return clean or "sym_flag"

    @classmethod
    def generate_script(
        cls,
        symbols: List[DecompilerSymbol],
        comments: List[DecompilerComment],
        bookmarks: List[DecompilerBookmark],
        base_addr: int = 0x400000,
        safe_labels: bool = True,
    ) -> str:
        """Generates radare2 command script (.r2) applying symbols, functions and comments."""
        lines = [
            "# Radare2 / Cutter Script - Generated by dotnet-packer-forensics",
            "e scr.color=false",
            f"# Base Address assumption: {hex(base_addr)}",
            "",
            "# 1. Flags and Functions",
        ]

        for s in symbols:
            name = cls.sanitize_flag(s.name) if safe_labels else s.name
            addr = hex(base_addr + s.rva)
            lines.append(f"f {name} @ {addr}")
            if s.is_function:
                size_param = f" {s.size}" if s.size > 0 else ""
                lines.append(f"af+ {addr} {name}{size_param}")

        lines.extend(["", "# 2. Comments"])
        for c in comments:
            addr = hex(base_addr + c.rva)
            clean_text = c.text.replace('"', '\\"').replace("\n", " | ")
            lines.append(f'CC- @ {addr}')
            lines.append(f'CC "{clean_text}" @ {addr}')

        lines.extend(["", "# 3. Bookmarks / Tags"])
        for b in bookmarks:
            addr = hex(base_addr + b.rva)
            tag_name = cls.sanitize_flag(f"bm_{b.category}_{b.comment[:20]}")
            lines.append(f"f {tag_name} @ {addr}")

        lines.append("")
        return "\n".join(lines)

    @classmethod
    def generate_runner_bat(cls, script_name: str = "r2_annotations.r2") -> str:
        """Generates a Windows Command Batch runner script for radare2."""
        return f"""@echo off
setlocal
if "%~1"=="" (
    echo Usage: %~nx0 ^<target_binary^>
    exit /b 1
)
r2 -q -i "%~dp0{script_name}" "%~1"
endlocal
"""

    @classmethod
    def generate_runner_sh(cls, script_name: str = "r2_annotations.r2") -> str:
        """Generates a POSIX Bash runner script for radare2."""
        return f"""#!/usr/bin/env bash
set -euo pipefail
if [ $# -lt 1 ]; then
    echo "Usage: $0 <target_binary>" >&2
    exit 1
fi
r2 -q -i "$(dirname "$0")/{script_name}" "$1"
"""
