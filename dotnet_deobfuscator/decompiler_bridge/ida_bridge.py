import json
import re
from typing import List

from .models import (
    CommentType,
    DecompilerBookmark,
    DecompilerComment,
    DecompilerSymbol,
)


class IDABridgeGenerator:
    """Generates IDA Pro IDAPython synchronization scripts and batch runners."""

    @staticmethod
    def sanitize_label(name: str) -> str:
        """Sanitizes identifier for IDA symbol naming rules."""
        if not name:
            return "sub_unnamed"
        clean = re.sub(r"[^a-zA-Z0-9_$]", "_", name)
        clean = re.sub(r"_+", "_", clean).strip("_")
        if not clean:
            clean = "sub_forensic"
        if clean[0].isdigit():
            clean = f"sub_{clean}"
        return clean[:250]

    @classmethod
    def generate_script(
        cls,
        symbols: List[DecompilerSymbol],
        comments: List[DecompilerComment],
        bookmarks: List[DecompilerBookmark],
        base_addr: int = 0x400000,
        safe_labels: bool = True,
    ) -> str:
        """Generates a complete, valid IDAPython script compatible with IDA Pro 7.x-9.x."""
        sym_payload = []
        for s in symbols:
            lbl = cls.sanitize_label(s.name) if safe_labels else s.name
            sym_payload.append({
                "name": lbl,
                "rva": s.rva,
                "size": s.size,
                "is_function": s.is_function,
                "type": s.symbol_type.value,
                "demangled": s.demangled_name,
            })

        cmt_payload = []
        for c in comments:
            cmt_payload.append({
                "rva": c.rva,
                "text": c.text,
                "comment_type": c.comment_type.value,
                "repeatable": c.is_repeatable,
            })

        bm_payload = []
        for b in bookmarks:
            bm_payload.append({
                "rva": b.rva,
                "category": b.category,
                "comment": b.comment,
            })

        sym_json = json.dumps(sym_payload, indent=4)
        cmt_json = json.dumps(cmt_payload, indent=4)
        bm_json = json.dumps(bm_payload, indent=4)

        return f'''"""
IDA Pro Headless Synchronization Script - Generated by dotnet-packer-forensics
Compatible with IDA Pro 7.x, 8.x, and 9.x Python 3 environments.
"""

import json
import sys

BASE_ADDR = {hex(base_addr)}
SYMBOLS_DATA = {sym_json}
COMMENTS_DATA = {cmt_json}
BOOKMARKS_DATA = {bm_json}


def run():
    try:
        import ida_auto
        import ida_bytes
        import ida_funcs
        import ida_nalt
        import ida_name
        import idc
    except ImportError:
        print("[!] IDA Pro modules not detected; running in standalone verification mode.")
        return

    print("[*] Waiting for IDA auto-analysis completion...")
    ida_auto.auto_wait()
    image_base = ida_nalt.get_imagebase()

    sym_count = 0
    for s in SYMBOLS_DATA:
        ea = image_base + s["rva"]
        name = s["name"]
        try:
            flags = getattr(ida_name, "SN_NOWARN", 1) | getattr(ida_name, "SN_NOCHECK", 0)
            ida_name.set_name(ea, name, flags)
            if s.get("is_function", False):
                ida_funcs.add_func(ea)
            sym_count += 1
        except Exception as e:
            print(f"[!] Warning: failed naming 0x{{ea:X}} as '{{name}}': {{e}}")

    cmt_count = 0
    for c in COMMENTS_DATA:
        ea = image_base + c["rva"]
        text = c["text"]
        ctype = c.get("comment_type", "plate")
        repeatable = c.get("repeatable", False)
        try:
            if ctype in ("anterior", "plate"):
                lines = text.split("\\n")
                for idx, line in enumerate(lines):
                    idc.update_extra_cmt(ea, idc.E_PREV + idx, line)
            elif ctype == "posterior":
                lines = text.split("\\n")
                for idx, line in enumerate(lines):
                    idc.update_extra_cmt(ea, idc.E_NEXT + idx, line)
            else:
                ida_bytes.set_cmt(ea, text, 1 if repeatable else 0)
            cmt_count += 1
        except Exception as e:
            print(f"[!] Warning: failed comment at 0x{{ea:X}}: {{e}}")

    bm_count = 0
    for idx, b in enumerate(BOOKMARKS_DATA):
        ea = image_base + b["rva"]
        desc = f"[{{b.get('category', 'Forensics')}}] {{b.get('comment', '')}}".strip()
        try:
            idc.put_bookmark(ea, 0, 0, 0, idx, desc)
            bm_count += 1
        except Exception:
            pass

    print(
        f"[+] IDA Forensics Bridge: {{sym_count}} symbols, {{cmt_count}} comments, "
        f"{{bm_count}} bookmarks applied."
    )


if __name__ == "__main__" or "ida_nalt" in sys.modules:
    run()
'''

    @classmethod
    def generate_runner_bat(
        cls,
        script_name: str = "ida_annotations.py",
    ) -> str:
        """Generates a Windows Command Batch runner script for headless IDA Pro."""
        return f"""@echo off
setlocal
if "%IDA_DIR%"=="" set IDA_DIR=C:\\Program Files\\IDA Professional 9.0
set IDA_EXE="%IDA_DIR%\\idat64.exe"
if not exist %IDA_EXE% (
    set IDA_EXE="idat64.exe"
)
if "%~1"=="" (
    echo Usage: %~nx0 ^<target_binary^>
    exit /b 1
)
set TARGET=%~1
set SCRIPT_PATH=%~dp0{script_name}

echo [*] Launching IDA Pro Headless Batch Session...
%IDA_EXE% -c -A -S"%SCRIPT_PATH%" "%TARGET%"
echo [+] IDA Pro synchronization complete.
endlocal
"""

    @classmethod
    def generate_runner_sh(
        cls,
        script_name: str = "ida_annotations.py",
    ) -> str:
        """Generates a POSIX Bash runner script for headless IDA Pro."""
        return f"""#!/usr/bin/env bash
set -euo pipefail
IDA_DIR="${{IDA_DIR:-/opt/idapro-9.0}}"
IDA_EXE="${{IDA_DIR}}/idat64"
if ! command -v "$IDA_EXE" &>/dev/null && [ ! -x "$IDA_EXE" ]; then
    IDA_EXE="idat64"
fi
if [ $# -lt 1 ]; then
    echo "Usage: $0 <target_binary>" >&2
    exit 1
fi
TARGET="$1"
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
SCRIPT_PATH="${{SCRIPT_DIR}}/{script_name}"

echo "[*] Launching IDA Pro Headless Batch Session..."
"$IDA_EXE" -c -A -S"$SCRIPT_PATH" "$TARGET"
echo "[+] IDA Pro synchronization complete."
"""
