import json
import re
from typing import List, Optional

from .models import (
    CommentType,
    DecompilerBookmark,
    DecompilerComment,
    DecompilerSymbol,
)


class GhidraBridgeGenerator:
    """Generates Ghidra headless post-analysis Python scripts and batch runners."""

    @staticmethod
    def sanitize_label(name: str) -> str:
        """Sanitizes identifier for Ghidra symbol label compliance."""
        if not name:
            return "sym_unnamed"
        clean = re.sub(r"[^a-zA-Z0-9_]", "_", name)
        clean = re.sub(r"_+", "_", clean).strip("_")
        if not clean:
            clean = "sym_sub"
        if clean[0].isdigit():
            clean = f"sym_{clean}"
        return clean

    @classmethod
    def generate_script(
        cls,
        symbols: List[DecompilerSymbol],
        comments: List[DecompilerComment],
        bookmarks: List[DecompilerBookmark],
        base_addr: int = 0x400000,
        safe_labels: bool = True,
    ) -> str:
        """Generates a complete, valid Python 3/Jython post-script for Ghidra headless analysis."""
        sym_payload = []
        for s in symbols:
            lbl = cls.sanitize_label(s.name) if safe_labels else s.name
            sym_payload.append({
                "name": lbl,
                "rva": s.rva,
                "size": s.size,
                "is_function": s.is_function,
                "type": s.symbol_type.value,
                "demangled": s.demangled_name,
            })

        cmt_payload = []
        for c in comments:
            cmt_payload.append({
                "rva": c.rva,
                "text": c.text,
                "comment_type": c.comment_type.value,
                "repeatable": c.is_repeatable,
            })

        bm_payload = []
        for b in bookmarks:
            bm_payload.append({
                "rva": b.rva,
                "category": b.category,
                "comment": b.comment,
            })

        sym_json = json.dumps(sym_payload, indent=4)
        cmt_json = json.dumps(cmt_payload, indent=4)
        bm_json = json.dumps(bm_payload, indent=4)

        return f'''# @category Forensics.DotNet
# @menupath Tools.Forensics.Apply DotNet Forensics Annotations
"""
Ghidra Post-Analysis Script - Generated by dotnet-packer-forensics
Applies synchronized forensic symbols, method boundaries, and telemetry comments.
"""

import json
import sys

BASE_ADDR = {hex(base_addr)}
SYMBOLS_DATA = {sym_json}
COMMENTS_DATA = {cmt_json}
BOOKMARKS_DATA = {bm_json}


def run():
    try:
        prog = currentProgram
        image_base = prog.getImageBase().getOffset()
    except NameError:
        print("[!] Ghidra environment globals not detected; skipping active injection.")
        return

    sym_count = 0
    for s in SYMBOLS_DATA:
        addr = toAddr(image_base + s["rva"])
        name = s["name"]
        try:
            createLabel(addr, name, True)
            if s.get("is_function", False):
                func = createFunction(addr, name)
                if func is None:
                    func = getFunctionAt(addr)
                if func and s.get("size", 0) > 0:
                    func.setBody(prog.getAddressFactory().getAddressSet(addr, addr.add(s["size"] - 1)))
            sym_count += 1
        except Exception as e:
            print(f"[!] Warning: failed applying symbol '{{name}}' at {{addr}}: {{e}}")

    cmt_count = 0
    for c in COMMENTS_DATA:
        addr = toAddr(image_base + c["rva"])
        text = c["text"]
        ctype = c.get("comment_type", "plate")
        try:
            if ctype == "plate":
                setPlateComment(addr, text)
            elif ctype == "eol":
                setEOLComment(addr, text)
            elif ctype == "repeatable":
                setRepeatableComment(addr, text)
            else:
                setPlateComment(addr, text)
            cmt_count += 1
        except Exception as e:
            print(f"[!] Warning: failed applying comment at {{addr}}: {{e}}")

    bm_count = 0
    for b in BOOKMARKS_DATA:
        addr = toAddr(image_base + b["rva"])
        try:
            createBookmark(addr, b.get("category", "Forensics"), b.get("comment", ""))
            bm_count += 1
        except Exception as e:
            print(f"[!] Warning: failed bookmark at {{addr}}: {{e}}")

    print(
        f"[+] Forensics Bridge: {{sym_count}} symbols, {{cmt_count}} comments, "
        f"{{bm_count}} bookmarks synchronized."
    )


if __name__ == "__main__" or "currentProgram" in globals():
    run()
'''

    @classmethod
    def generate_runner_bat(
        cls,
        script_name: str = "ghidra_annotations.py",
        project_dir: str = "ghidra_project",
        project_name: str = "ForensicSession",
    ) -> str:
        """Generates a Windows Command Batch runner script for headless Ghidra."""
        return f"""@echo off
setlocal
if "%GHIDRA_HOME%"=="" (
    echo [!] GHIDRA_HOME environment variable is not defined.
    echo [!] Please set GHIDRA_HOME to your Ghidra installation root.
    exit /b 1
)
set HEADLESS="%GHIDRA_HOME%\\support\\analyzeHeadless.bat"
if not exist %HEADLESS% (
    echo [!] analyzeHeadless.bat was not found under: %HEADLESS%
    exit /b 1
)
if "%~1"=="" (
    echo Usage: %~nx0 ^<target_binary^>
    exit /b 1
)
set TARGET=%~1
set PROJ_DIR=%~dp0{project_dir}
set SCRIPT_PATH=%~dp0{script_name}

echo [*] Launching Ghidra Headless Analyzer...
call %HEADLESS% "%PROJ_DIR%" "{project_name}" -import "%TARGET%" -postScript "%SCRIPT_PATH%" -overwrite
echo [+] Headless Ghidra synchronization complete.
endlocal
"""

    @classmethod
    def generate_runner_sh(
        cls,
        script_name: str = "ghidra_annotations.py",
        project_dir: str = "ghidra_project",
        project_name: str = "ForensicSession",
    ) -> str:
        """Generates a POSIX Bash runner script for headless Ghidra."""
        return f"""#!/usr/bin/env bash
set -euo pipefail
if [ -z "${{GHIDRA_HOME:-}}" ]; then
    echo "[!] GHIDRA_HOME environment variable is not defined." >&2
    exit 1
fi
HEADLESS="${{GHIDRA_HOME}}/support/analyzeHeadless"
if [ ! -x "$HEADLESS" ]; then
    echo "[!] analyzeHeadless was not found or is not executable: $HEADLESS" >&2
    exit 1
fi
if [ $# -lt 1 ]; then
    echo "Usage: $0 <target_binary>" >&2
    exit 1
fi
TARGET="$1"
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
PROJ_DIR="${{SCRIPT_DIR}}/{project_dir}"
SCRIPT_PATH="${{SCRIPT_DIR}}/{script_name}"

echo "[*] Launching Ghidra Headless Analyzer..."
"$HEADLESS" "$PROJ_DIR" "{project_name}" -import "$TARGET" -postScript "$SCRIPT_PATH" -overwrite
echo "[+] Headless Ghidra synchronization complete."
"""
